"""Generate the README evaluation table from the versioned result JSON.

The script publishes only live runs from a clean worktree. A Replay document is
recorded evidence that the harness works, not a measurement of the model, so it
never contributes a row. When no live run exists, the table says so instead of
printing a result that has not happened.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from .answer_key import SCENARIOS
from .answer_key import scenario as scenario_by_name
from .results import EVIDENCE_LIVE, load_all

BEGIN = "<!-- BEGIN EVAL RESULTS (generated by evals/harness/pagerless_eval/table.py) -->"
END = "<!-- END EVAL RESULTS -->"
REPO_ROOT = Path(__file__).resolve().parents[3]
README = REPO_ROOT / "README.md"
RESULTS = REPO_ROOT / "evals" / "results"


def render(documents: list[dict[str, Any]]) -> str:
    """Render the block between the README markers."""
    live = [
        document
        for document in documents
        if document["evidence"] == EVIDENCE_LIVE and not document["pagerlessDirty"]
    ]
    runs = [run for document in live for run in document["runs"]]
    if not runs:
        return "\n".join(
            [
                "No live evaluation has been published yet. `make eval` writes one versioned",
                "document per batch under `evals/results`, and this table is generated from those",
                "documents by `make eval-table`. The credential-free Replay subset runs in CI as a",
                "harness check and is not evidence of model performance. The evaluator contract,",
                "scoring rules, and JSON schema are in [docs/evaluation.md](docs/evaluation.md).",
            ]
        )

    models = ", ".join(sorted({document["model"]["label"] for document in live}))
    repeats = ", ".join(sorted({str(document["repeats"]) for document in live}))
    covered = sorted({run["scenario"] for run in runs}, key=_scenario_order)
    sentences = [
        f"**Model:** {models}  ",
        f"**Runs:** {len(runs)} across {len(covered)} Scenarios "
        f"({', '.join(covered)}), {repeats} repeat(s) each.  ",
        f"**Source:** {len(live)} result document(s) under `evals/results`.  ",
        "Results are graded by deterministic code against the answer key, not by the model.",
    ]

    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for run in runs:
        grouped[run["scenario"]].append(run)

    lines = [
        *sentences,
        "",
        "| Scenario | Action | Pass | Mitigated | Fail | Mean time to Recovered | Mean cost |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in covered:
        items = grouped[name]
        recovered = [
            item["timeToRecoveredSeconds"]
            for item in items
            if item["phase"] == "Recovered" and item["timeToRecoveredSeconds"] is not None
        ]
        costs = [
            item["usage"]["costUSD"]
            for item in items
            if isinstance(item["usage"].get("costUSD"), (int, float))
        ]
        lines.append(
            "| {scenario} | {action} | {passed} | {mitigated} | {failed} | {seconds} | {cost} |".format(
                scenario=f"{scenario_by_name(name).number}. {name}",
                action=", ".join(sorted({str(item["action"]) for item in items})),
                passed=sum(item["result"] == "pass" for item in items),
                mitigated=sum(item["result"] == "mitigated" for item in items),
                failed=sum(item["result"] == "fail" for item in items),
                seconds=_duration(sum(recovered) / len(recovered)) if recovered else "n/a",
                cost=_cost(sum(costs) / len(costs)) if costs else "n/a",
            )
        )
    total_cost = sum(
        item["usage"]["costUSD"] for item in runs if isinstance(item["usage"].get("costUSD"), (int, float))
    )
    lines.append(
        "| **Total** | | **{passed}** | **{mitigated}** | **{failed}** | | **{cost}** |".format(
            passed=sum(item["result"] == "pass" for item in runs),
            mitigated=sum(item["result"] == "mitigated" for item in runs),
            failed=sum(item["result"] == "fail" for item in runs),
            cost=_cost(total_cost),
        )
    )
    return "\n".join(lines)


def replace_block(readme: str, block: str) -> str:
    """Replace the generated block, refusing to guess when the markers are absent."""
    if BEGIN not in readme or END not in readme:
        raise ValueError(f"README.md does not carry the evaluation markers {BEGIN!r} and {END!r}")
    before, remainder = readme.split(BEGIN, 1)
    _, after = remainder.split(END, 1)
    return f"{before}{BEGIN}\n{block}\n{END}{after}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--print", action="store_true", help="print the rendered block")
    parser.add_argument("--update-readme", action="store_true", help="rewrite README.md")
    parser.add_argument("--check", action="store_true", help="exit non-zero when README.md is out of date")
    parser.add_argument("--readme", type=Path, default=README)
    parser.add_argument("--results-dir", type=Path, default=RESULTS)
    arguments = parser.parse_args(argv)

    try:
        block = render(load_all(arguments.results_dir))
        readme = arguments.readme.read_text(encoding="utf-8")
        updated = replace_block(readme, block)
    except (OSError, ValueError) as error:
        print(f"make eval-table failed: {error}", file=sys.stderr)
        return 1

    if arguments.print:
        print(block)
    if arguments.update_readme:
        arguments.readme.write_text(updated, encoding="utf-8")
        print(f"Updated {arguments.readme} from {arguments.results_dir}")
    if arguments.check:
        if updated != readme:
            print(
                "README.md's evaluation table is out of date. Run make eval-table.",
                file=sys.stderr,
            )
            return 1
        print("README.md's evaluation table is current.")
    if not (arguments.print or arguments.update_readme or arguments.check):
        print(block)
    return 0


def _scenario_order(name: str) -> int:
    return next((item.number for item in SCENARIOS if item.name == name), 10_000)


def _duration(seconds: float) -> str:
    minutes, remainder = divmod(int(round(seconds)), 60)
    return f"{minutes}m {remainder}s" if minutes else f"{remainder}s"


def _cost(value: float) -> str:
    return f"${value:.4f}"


if __name__ == "__main__":
    raise SystemExit(main())
