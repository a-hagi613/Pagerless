#!/usr/bin/env bash
# Regenerates Formula/kubectl-page.rb in the a-hagi613/homebrew-tap repository
# from the release's own checksum file.
#
# This script is the only writer of the formula. It never copies a checksum from
# a previous release and never lets GoReleaser's deprecated formula generator
# write one, so a formula can only describe the archives that the checksum file
# lists. It fails when any of the four archive checksums is missing.
#
# Usage:
#   homebrew-formula.sh --checksums FILE --version VERSION [--output PATH]
#   homebrew-formula.sh --checksums FILE --version VERSION --pull-request
#
# --pull-request needs HOMEBREW_TAP_TOKEN with write access to the tap
# repository. It commits the formula to a per-release branch and opens the Pull
# Request; a rerun with an unchanged formula does nothing.
set -euo pipefail

# shellcheck source=hack/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/../../hack/lib.sh"

checksums=""
version=""
output=""
pull_request=false
tap="a-hagi613/homebrew-tap"
repo="a-hagi613/pagerless"

usage() {
	cat >&2 <<'EOF'
Usage: homebrew-formula.sh --checksums FILE --version VERSION [--output PATH] [--pull-request]

  --checksums FILE   The release checksum file (checksums.txt).
  --version VERSION  The release version without the leading v, such as 2.0.0.
  --output PATH      Write the formula here instead of opening a Pull Request.
  --pull-request     Commit the formula to a branch in the tap and open the PR.
                     Needs HOMEBREW_TAP_TOKEN.
  --tap OWNER/NAME   Tap repository. Default: a-hagi613/homebrew-tap
  --repo OWNER/NAME  Release repository. Default: a-hagi613/pagerless
EOF
}

while [ $# -gt 0 ]; do
	case "$1" in
	--checksums)
		checksums="${2:?--checksums needs a file}"
		shift 2
		;;
	--version)
		version="${2:?--version needs a value}"
		shift 2
		;;
	--output)
		output="${2:?--output needs a path}"
		shift 2
		;;
	--pull-request)
		pull_request=true
		shift
		;;
	--tap)
		tap="${2:?--tap needs OWNER/NAME}"
		shift 2
		;;
	--repo)
		repo="${2:?--repo needs OWNER/NAME}"
		shift 2
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		usage
		die "unknown argument $1"
		;;
	esac
done

[ -n "$checksums" ] || {
	usage
	die "--checksums is required"
}
[ -n "$version" ] || {
	usage
	die "--version is required"
}
[ -f "$checksums" ] || die "the checksum file $checksums does not exist."
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([.-][0-9A-Za-z.-]+)?$ ]] ||
	die "$version is not a release version without a leading v."
if [ "$pull_request" = true ] && [ -n "$output" ]; then
	die "--output and --pull-request are mutually exclusive."
fi

checksum_for() {
	local archive="$1" line
	line="$(awk -v archive="$archive" '$2 == archive { print $1 }' "$checksums")"
	[ -n "$line" ] || die "the checksum file $checksums has no line for $archive."
	printf '%s\n' "$line"
}

archive_url() {
	printf 'https://github.com/%s/releases/download/v%s/kubectl-page_%s_%s_%s.tar.gz' \
		"$repo" "$version" "$version" "$1" "$2"
}

render_formula() {
	local darwin_amd64 darwin_arm64 linux_amd64 linux_arm64
	darwin_amd64="$(checksum_for "kubectl-page_${version}_darwin_amd64.tar.gz")"
	darwin_arm64="$(checksum_for "kubectl-page_${version}_darwin_arm64.tar.gz")"
	linux_amd64="$(checksum_for "kubectl-page_${version}_linux_amd64.tar.gz")"
	linux_arm64="$(checksum_for "kubectl-page_${version}_linux_arm64.tar.gz")"

	cat <<EOF
# Generated by scripts/release/homebrew-formula.sh from the release's checksum
# file. Do not edit: regenerate it for each release.
class KubectlPage < Formula
  desc "kubectl plugin that investigates Kubernetes Targets as Pagerless Pages"
  homepage "https://github.com/${repo}"
  license "Apache-2.0"

  on_macos do
    if Hardware::CPU.arm?
      url "$(archive_url darwin arm64)"
      sha256 "${darwin_arm64}"
    else
      url "$(archive_url darwin amd64)"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "$(archive_url linux arm64)"
      sha256 "${linux_arm64}"
    else
      url "$(archive_url linux amd64)"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "kubectl-page"
  end

  test do
    assert_match "kubectl-page #{version}", shell_output("#{bin}/kubectl-page version")
  end
end
EOF
}

if [ "$pull_request" = false ]; then
	output="${output:-Formula/kubectl-page.rb}"
	mkdir -p "$(dirname "$output")"
	render_formula >"$output"
	echo "wrote $output for v${version}"
	exit 0
fi

require_commands git gh
[ -n "${HOMEBREW_TAP_TOKEN:-}" ] ||
	die "--pull-request needs HOMEBREW_TAP_TOKEN with write access to $tap."

work="$(mktemp -d "${TMPDIR:-/tmp}/pagerless-homebrew-tap.XXXXXXXX")"
trap 'rm -rf "$work"' EXIT

git clone --quiet --depth=1 "https://x-access-token:${HOMEBREW_TAP_TOKEN}@github.com/${tap}.git" "$work/tap"
mkdir -p "$work/tap/Formula"
render_formula >"$work/tap/Formula/kubectl-page.rb"

if git -C "$work/tap" diff --quiet -- Formula/kubectl-page.rb; then
	echo "Formula/kubectl-page.rb in $tap already describes v${version}; nothing to do."
	exit 0
fi

branch="kubectl-page-${version}"
git -C "$work/tap" checkout --quiet -b "$branch"
git -C "$work/tap" -c user.name="pagerless-release" -c user.email="release@pagerless.dev" \
	add Formula/kubectl-page.rb
git -C "$work/tap" -c user.name="pagerless-release" -c user.email="release@pagerless.dev" \
	commit --quiet --message "kubectl-page ${version}

Generated by scripts/release/homebrew-formula.sh from the v${version} release
checksum file."
git -C "$work/tap" push --quiet origin "$branch"

if GH_TOKEN="$HOMEBREW_TAP_TOKEN" gh pr list --repo "$tap" --head "$branch" --state open --json number --jq '.[].number' | grep -q .; then
	echo "an open Pull Request for $branch already exists in $tap"
	exit 0
fi

GH_TOKEN="$HOMEBREW_TAP_TOKEN" gh pr create --repo "$tap" --base main --head "$branch" \
	--title "kubectl-page ${version}" \
	--body "Regenerates Formula/kubectl-page.rb from the v${version} release checksum file.

Generated by scripts/release/homebrew-formula.sh in https://github.com/${repo}."
