#!/usr/bin/env bash
# Renders plugins/page.yaml, the Krew plugin manifest that a checkout installs
# with `kubectl krew install --manifest=plugins/page.yaml`, from the release's
# own checksum file.
#
# The release workflow runs this script against dist/checksums.txt, so the
# manifest and the archives it points at are derived from one file and cannot
# disagree. The script fails when any of the four archive checksums is missing.
#
# Usage:
#   render-krew-manifest.sh --checksums FILE --version VERSION \
#     [--base-url URL] [--output PATH]
set -euo pipefail

# shellcheck source=hack/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/../../hack/lib.sh"

checksums=""
version=""
base_url=""
output="plugins/page.yaml"

usage() {
	cat >&2 <<'EOF'
Usage: render-krew-manifest.sh --checksums FILE --version VERSION [--base-url URL] [--output PATH]

  --checksums FILE  The release checksum file (checksums.txt).
  --version VERSION The release version without the leading v, such as 2.0.0.
  --base-url URL    Where the archives are served. Default:
                    https://github.com/a-hagi613/pagerless/releases/download/vVERSION
  --output PATH     Where to write the manifest. Default: plugins/page.yaml
EOF
}

while [ $# -gt 0 ]; do
	case "$1" in
	--checksums)
		checksums="${2:?--checksums needs a file}"
		shift 2
		;;
	--version)
		version="${2:?--version needs a value}"
		shift 2
		;;
	--base-url)
		base_url="${2:?--base-url needs a URL}"
		shift 2
		;;
	--output)
		output="${2:?--output needs a path}"
		shift 2
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		usage
		die "unknown argument $1"
		;;
	esac
done

[ -n "$checksums" ] || {
	usage
	die "--checksums is required"
}
[ -n "$version" ] || {
	usage
	die "--version is required"
}
[ -f "$checksums" ] || die "the checksum file $checksums does not exist."
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([.-][0-9A-Za-z.-]+)?$ ]] ||
	die "$version is not a release version without a leading v."
base_url="${base_url:-https://github.com/a-hagi613/pagerless/releases/download/v${version}}"
base_url="${base_url%/}"

# checksum_for prints the SHA-256 recorded for one archive, or fails when the
# checksum file does not carry that archive.
checksum_for() {
	local archive="$1" line
	line="$(awk -v archive="$archive" '$2 == archive { print $1 }' "$checksums")"
	[ -n "$line" ] || die "the checksum file $checksums has no line for $archive."
	printf '%s\n' "$line"
}

platform() {
	local os="$1" arch="$2" archive sha
	archive="kubectl-page_${version}_${os}_${arch}.tar.gz"
	sha="$(checksum_for "$archive")"
	printf '%s %s %s %s\n' "$os" "$arch" "$sha" "$archive"
}

manifest="$(
	cat <<'EOF'
# Generated by scripts/release/render-krew-manifest.sh from the release's
# checksum file. Do not edit: regenerate it with
#   scripts/release/render-krew-manifest.sh --checksums checksums.txt --version VERSION
EOF
	cat <<EOF
apiVersion: krew.googlecontainertools.github.com/v1alpha2
kind: Plugin
metadata:
  name: page
spec:
  version: v${version}
  homepage: https://github.com/a-hagi613/pagerless
  shortDescription: Ask why a Kubernetes workload is failing and follow the evidence
  description: |
    kubectl page opens an investigation from a terminal question and streams the
    agent's tool calls, cited evidence, and answer. It uses the same API and
    conversation history as the dashboard. Ctrl-C detaches from the stream and
    leaves the turn running; stopping a turn is an explicit command.
  caveats: |
    Pagerless must already be installed in the cluster. Install the chart with
    helm install pagerless oci://ghcr.io/a-hagi613/charts/pagerless
    --namespace pagerless --create-namespace, then run kubectl page --help.
    The plugin discovers the installed Service through the current kube context
    and forwards a local port; pass --address to use a reachable address
    directly. Export the operator token as PAGERLESS_TOKEN or pass
    --token-file. The token is never a flag value and never appears in a URL.
  platforms:
EOF
	for pair in linux/amd64 linux/arm64 darwin/amd64 darwin/arm64; do
		os="${pair%/*}"
		arch="${pair#*/}"
		# An assignment keeps `set -e` effective when the checksum is missing.
		entry="$(platform "$os" "$arch")"
		read -r _ _ sha archive <<<"$entry"
		cat <<EOF
    - bin: kubectl-page
      uri: ${base_url}/${archive}
      sha256: ${sha}
      selector:
        matchLabels:
          os: ${os}
          arch: ${arch}
EOF
	done
)"

mkdir -p "$(dirname "$output")"
printf '%s\n' "$manifest" >"$output"
echo "wrote $output for v${version}"
